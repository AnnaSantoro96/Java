package JavaBase.Variables;

public class RectangleArea {
    static void main() {
        //RECTANGLE VARIABLES
        int length = 4;
        int width = 6;
        int area = length * width;

        // PRINT VARIABLES
        System.out.println("Length is: " + length);
        System.out.println("Width is: " + width);
        System.out.println("Area of the rectangle is: " + area);
    }
}
